def plot_actuator_trajectory(
    trajectory: list[opt.TrainState],
    limits: mpc_spec.MPCLimits,
    spec: mpc_spec.MPCSpec,
    use_estop: bool = False,
    fig_title: str = "Actuator Trajectory",
    fig_kwds: dict | None = None,
) -> mpl_fig.Figure:
    """Plot actuator state summaries over an MPC trajectory.

    The figure includes leg length, leg velocity, leg acceleration,
    and top and bottom joint angles.

    Parameters
    ----------
    trajectory :
        Sequence of MPC train states.
    limits :
        MPC limits, used for actuator limit lines.
    spec :
        MPC specification, used for timing and geometry.
    use_estop :
        True to use estop variants.
    fig_title :
        Figure super title.
    fig_kwds :
        Extra keyword arguments passed to :func:`matplotlib.pyplot.subplots`.

    Returns
    -------
    fig :
        Figure with actuator length, velocity, acceleration, and joint-angle
        trajectories.
    """
    if fig_kwds is None:
        fig_kwds = {}
    fig, axes = plt.subplots(
        nrows=2,
        ncols=2,
        figsize=(16, 10),
        gridspec_kw={"wspace": 0.35},
        **fig_kwds,
    )
    fig.suptitle(fig_title, fontsize=16)

    times = np.arange(0, len(trajectory), dtype=float) * spec.dt

    colors = [mpl.colormaps["viridis"](c) for c in np.linspace(0, 1, 6)]

    ###############
    # leg lengths #
    ###############

    if not use_estop:
        leg_pos_vals = np.array([ts.leg_pos[0] for ts in trajectory])
        leg_pos_title = "Leg Lengths"
    else:
        leg_pos_vals = np.array([ts.leg_pos_estop[0] for ts in trajectory])
        leg_pos_title = "Leg Lengths Estop"

    ax_pos = axes[0, 0]
    ax_pos.set_title(leg_pos_title)
    ax_pos.set_xlabel("[s]")
    ax_pos.set_ylabel("[m]")
    ax_pos.set_xlim(times[0], times[-1])
    ax_pos.set_ylim(*_get_limits(leg_pos_vals))
    ax_pos.grid()

    for leg_num, color in zip(range(leg_pos_vals.shape[1]), colors):
        ax_pos.plot(
            times,
            leg_pos_vals[:, leg_num],
            color=color,
            label=f"Leg {leg_num + 1}",
        )
    ax_pos.axhline(
        y=limits.leg_min,
        linestyle="-",
        alpha=0.5,
        color="red",
        label="Min Length",
    )
    ax_pos.axhline(
        y=limits.leg_max,
        linestyle="-",
        alpha=0.5,
        color="red",
        label="Max Length",
    )
    ax_pos.legend()

    ##################
    # leg velocities #
    ##################

    leg_vel_vals = np.array([ts.leg_vel[0] for ts in trajectory])

    ax_vel = axes[0, 1]
    ax_vel.set_title("Leg Velocities")
    ax_vel.set_xlabel("[s]")
    ax_vel.set_ylabel("[m/s]")
    ax_vel.set_xlim(times[0], times[-1])
    ax_vel.set_ylim(*_get_limits(leg_vel_vals))
    ax_vel.grid()

    for leg_num, color in zip(range(leg_vel_vals.shape[1]), colors):
        ax_vel.plot(
            times,
            leg_vel_vals[:, leg_num],
            color=color,
            label=f"Leg {leg_num + 1}",
        )
    ax_vel.axhline(
        y=-limits.max_leg_vel,
        linestyle="-",
        alpha=0.5,
        color="red",
        label="Min Velocity",
    )
    ax_vel.axhline(
        y=limits.max_leg_vel,
        linestyle="-",
        alpha=0.5,
        color="red",
        label="Max Velocity",
    )
    ax_vel.legend()

    #####################
    # leg accelerations #
    #####################

    leg_acc_vals = np.array(
        [(ts.leg_vel[1] - ts.leg_vel[0]) / spec.dt for ts in trajectory]
    )

    ax_acc = axes[1, 0]
    ax_acc.set_title("Leg Accelerations")
    ax_acc.set_xlabel("[s]")
    ax_acc.set_ylabel("[m/s^2]")
    ax_acc.set_xlim(times[0], times[-1])
    ax_acc.set_ylim(*_get_limits(leg_acc_vals))
    ax_acc.grid()

    for leg_num, color in zip(range(leg_acc_vals.shape[1]), colors):
        ax_acc.plot(
            times,
            leg_acc_vals[:, leg_num],
            color=color,
            label=f"Leg {leg_num + 1}",
        )
    ax_acc.legend()

    ################
    # joint angles #
    ################

    top_joint_angles = np.degrees(
        np.array([ts.leg_ang[0, :6] for ts in trajectory])
    )

    bot_joint_angles = np.degrees(
        np.array([ts.leg_ang[0, 6:] for ts in trajectory])
    )

    ax_angles = axes[1, 1]
    ax_angles.set_title("Joint Angles")
    ax_angles.set_xlabel("[s]")
    ax_angles.set_ylabel("[deg]")
    ax_angles.set_xlim(times[0], times[-1])
    y_lim_data = jnp.concatenate(
        [top_joint_angles.flatten(), bot_joint_angles.flatten()]
    )
    ax_angles.set_ylim(*_get_limits(y_lim_data))
    ax_angles.grid()

    joint_colors = [mpl.colormaps["viridis"](c) for c in np.linspace(0, 1, 12)]

    for leg_num, color in zip(
        range(top_joint_angles.shape[1]), joint_colors[:6]
    ):
        ax_angles.plot(
            times,
            top_joint_angles[:, leg_num],
            color=color,
            label=f"Top Joint {leg_num + 1}",
        )
    for leg_num, color in zip(
        range(bot_joint_angles.shape[1]), joint_colors[6:]
    ):
        ax_angles.plot(
            times,
            bot_joint_angles[:, leg_num],
            color=color,
            label=f"Bottom Joint {leg_num + 1}",
        )
    ax_angles.axhline(
        y=np.degrees(limits.joint_max_angle),
        linestyle="-",
        alpha=0.5,
        color="red",
        label="Max Joint Angle",
    )
    ax_angles.legend()

    return fig
