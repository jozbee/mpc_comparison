@functools.partial(jax.jit, static_argnames=["spec"])
def human_angle_vel(ts: opt.TrainState, spec: mpc_spec.MPCSpec) -> jax.Array:
    """Human angular velocity.

    Parameters
    ----------
    ts : opt.TrainState
        The train state containing the state and control trajectories.
    spec :
        MPC specification (unused, kept for call-site consistency).

    Returns
    -------
    omega :
        The human angular velocity.
    """
    return ts.omega_head[0]


@functools.partial(jax.jit, static_argnames=["spec"])
def table_angle_vel(ts: opt.TrainState, spec: mpc_spec.MPCSpec) -> jax.Array:
    """Table angular velocity.

    Parameters
    ----------
    ts : opt.TrainState
        The train state containing the state and control trajectories.
    spec :
        MPC specification (unused, kept for call-site consistency).

    Returns
    -------
    omega :
        The table angular velocity.
    """
    return comp.ang_vel(ts.y_quat[0], ts.y_quat[1], spec.dt)


@functools.partial(jax.jit, static_argnames=["spec"])
def human_angle_acc(ts: opt.TrainState, spec: mpc_spec.MPCSpec) -> jax.Array:
    """Human angular acceleration.

    Parameters
    ----------
    ts : opt.TrainState
        The train state containing the state and control trajectories.
    spec :
        MPC specification (unused, kept for call-site consistency).

    Returns
    -------
    alpha :
        The human angular acceleration.
    """
    # off-by-one, which shouldn't be a big deal for visualization...
    # same comment applies to a lot of the functions here...
    return (ts.omega_head[1] - ts.omega_head[0]) / spec.dt


@functools.partial(jax.jit, static_argnames=["spec"])
def table_angle_acc(ts: opt.TrainState, spec: mpc_spec.MPCSpec) -> jax.Array:
    """Table angular acceleration.

    Parameters
    ----------
    ts : opt.TrainState
        The train state containing the state and control trajectories.
    spec :
        MPC specification (unused, kept for call-site consistency).

    Returns
    -------
    alpha :
        The table angular acceleration.
    """
    q0 = ts.y_quat[0]
    q1 = ts.y_quat[1]
    q2 = ts.y_quat[2]
    ome0 = comp.ang_vel(q0, q1, spec.dt)
    ome1 = comp.ang_vel(q1, q2, spec.dt)
    return (ome1 - ome0) / spec.dt


@functools.partial(jax.jit, static_argnames=["spec"])
def table_angle(ts: opt.TrainState, spec: mpc_spec.MPCSpec) -> jax.Array:
    """Table angle.

    Parameters
    ----------
    ts : opt.TrainState
        The train state containing the state and control trajectories.
    spec :
        MPC specification (unused, kept for call-site consistency).

    Returns
    -------
    rpy :
        The table roll, pitch, and yaw angles in degrees.
    """
    tilt = jnp.degrees(ts.euler_ang[0][:2])
    yaw = jnp.atleast_1d(jnp.degrees(ts.y_yaw[0]))
    return jnp.concatenate([tilt, yaw])


@functools.partial(jax.jit, static_argnames=["spec"])
def table_pos(ts: opt.TrainState, spec: mpc_spec.MPCSpec) -> jax.Array:
    """Table position.

    Parameters
    ----------
    ts : opt.TrainState
        The train state containing the state and control trajectories.
    spec :
        MPC specification (unused, kept for call-site consistency).

    Returns
    -------
    pos :
        The table position as a 3-element array ``[x, y, z]``.
    """
    return ts.y_xyz[0]


@functools.partial(jax.jit, static_argnames=["spec"])
def table_vel(ts: opt.TrainState, spec: mpc_spec.MPCSpec) -> jax.Array:
    """Table velocity.

    Parameters
    ----------
    ts : opt.TrainState
        The train state containing the state and control trajectories.
    spec :
        MPC specification (unused, kept for call-site consistency).

    Returns
    -------
    vel :
        The table velocity as a 3-element array ``[x_dot, y_dot, z_dot]``.
    """
    return (ts.y_xyz[1] - ts.y_xyz[0]) / spec.dt


@functools.partial(jax.jit, static_argnames=["spec"])
def table_acc(ts: opt.TrainState, spec: mpc_spec.MPCSpec) -> jax.Array:
    """Table acceleration.

    Parameters
    ----------
    ts : opt.TrainState
        The train state containing the state and control trajectories.
    spec :
        MPC specification (unused, kept for call-site consistency).

    Returns
    -------
    acc :
        The table acceleration as a 3-element array
        ``[x_dot2, y_dot2, z_dot2]``.
    """
    vel0 = (ts.y_xyz[1] - ts.y_xyz[0]) / spec.dt
    vel1 = (ts.y_xyz[2] - ts.y_xyz[1]) / spec.dt
    return (vel1 - vel0) / spec.dt


@functools.partial(jax.jit, static_argnames=["spec"])
def human_vel(ts: opt.TrainState, spec: mpc_spec.MPCSpec) -> jax.Array:
    """Human velocity.

    Parameters
    ----------
    ts : opt.TrainState
        The train state containing the state and control trajectories.
    spec :
        MPC specification used for rotation conventions.

    Returns
    -------
    vel :
        The human velocity as a 3-element array ``[x_dot, y_dot, z_dot]`` in the
        human frame.
    """
    I = np.eye(3)
    q0 = comp.inv_ty(ts.y_quat[0], ts.y_yaw[0])
    R0 = comp.rot(q0)
    q1 = comp.inv_ty(ts.y_quat[1], ts.y_yaw[1])
    R1 = comp.rot(q1)
    pos0 = ts.y_xyz[0] + (R0 - I) @ spec.human_displacement
    pos1 = ts.y_xyz[1] + (R1 - I) @ spec.human_displacement
    return R0.T @ (pos1 - pos0) / spec.dt


@functools.partial(jax.jit, static_argnames=["spec"])
def human_acc(ts: opt.TrainState, spec: mpc_spec.MPCSpec) -> jax.Array:
    """Human acceleration.

    Parameters
    ----------
    ts : opt.TrainState
        The train state containing the state and control trajectories.
    spec :
        MPC specification used for rotation conventions.

    Returns
    -------
    acc :
        The human acceleration as a 3-element array ``[x_dot2, y_dot2, z_dot2]``
        in the human frame.
    """
    I = np.eye(3)
    q0 = comp.inv_ty(ts.y_quat[0], ts.y_yaw[0])
    R0 = comp.rot(q0)
    q1 = comp.inv_ty(ts.y_quat[1], ts.y_yaw[1])
    R1 = comp.rot(q1)
    q2 = comp.inv_ty(ts.y_quat[2], ts.y_yaw[2])
    R2 = comp.rot(q2)
    pos0 = ts.y_xyz[0] + (R0 - I) @ spec.human_displacement
    pos1 = ts.y_xyz[1] + (R1 - I) @ spec.human_displacement
    pos2 = ts.y_xyz[2] + (R2 - I) @ spec.human_displacement
    return R0.T @ ((pos2 - 2.0 * pos1 + pos0) / spec.dt**2 + mpc_spec.gravity)


@jax.jit
def _table_pos(ts: opt.TrainState) -> jax.Array:
    xyz = ts.y_xyz[0]
    q = jnp.concatenate([ts.y_quat[0], jnp.array([0.0])])
    return jnp.concatenate([xyz, q])


@functools.partial(jax.jit, static_argnames=["spec"])
def _human_pos(ts: opt.TrainState, spec: mpc_spec.MPCSpec) -> jax.Array:
    q = comp.inv_ty(ts.y_quat[0], ts.y_yaw[0])
    R = comp.rot(q)
    I = np.eye(3)
    xyz = ts.y_xyz[0] + (R - I) @ spec.human_displacement
    return jnp.concatenate([xyz, q])


def _way_from_train(
    trajectory: list[opt.TrainState],
    spec: mpc_spec.MPCSpec,
) -> tuple[np.ndarray, np.ndarray]:
    """Convert train states to table and human waypoints."""
    table = np.array([_table_pos(ts) for ts in trajectory])
    human = np.array([_human_pos(ts, spec) for ts in trajectory])
    return table, human


