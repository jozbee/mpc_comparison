def plot_vestibular_trajectory(
    trajectory: list[opt.TrainState],
    limits: mpc_spec.MPCLimits,
    spec: mpc_spec.MPCSpec,
    fig_title: str = "Vestibular Trajectory",
    fig_kwds: dict | None = None,
) -> mpl_fig.Figure:
    """Plot vestibular outputs for irl and simulated over an MPC trajectory.

    Parameters
    ----------
    trajectory :
        Sequence of MPC train states.
    limits :
        MPC limits, used for plot limits.
    spec :
        MPC specification, used for time axis spacing.
    fig_title :
        Figure super title.
    fig_kwds :
        Extra keyword arguments passed to :func:`matplotlib.pyplot.subplots`.

    Returns
    -------
    fig :
        Figure with angular velocity and linear acceleration panels.
        Each panel includes the irl signal and the simulated reference signal.
    """
    #########
    # setup #
    #########

    if fig_kwds is None:
        fig_kwds = {}
    gridspec_kw = {
        # "height_ratios": [1.0, 1.0, 1.0, 1.0],
        # "width_ratios": [1.0, 1.0, 1.0],
        "wspace": 0.35,
        "hspace": 0.35,
    }
    fig, axes = plt.subplots(
        nrows=2, ncols=3, gridspec_kw=gridspec_kw, figsize=(16, 8), **fig_kwds
    )
    fig.suptitle(fig_title, fontsize=16)

    times = jnp.arange(0, len(trajectory), dtype=float) * spec.dt

    ####################
    # angular velocity #
    ####################

    # compute
    @jax.jit
    def get_omegas(ts: opt.TrainState) -> tuple[jax.Array, jax.Array]:
        return ts.y_vest_irl[0, 3:], ts.y_vest_sim[0, 3:]

    omegas = jnp.array([get_omegas(ts)[0] for ts in trajectory])
    omegas_ref = jnp.array([get_omegas(ts)[1] for ts in trajectory])

    # plot
    _simple_plot(
        axis=axes[0, 0],
        time=times,
        data=jnp.rad2deg(omegas[:, 0]),
        title="X Angular Velocity",
        data_label="[deg/s]",
        min_limit=-jnp.rad2deg(limits.max_angle_vel),
        max_limit=jnp.rad2deg(limits.max_angle_vel),
        reference=jnp.rad2deg(omegas_ref[:, 0]),
    )
    _simple_plot(
        axis=axes[0, 1],
        time=times,
        data=jnp.rad2deg(omegas[:, 1]),
        title="Y Angular Velocity",
        data_label="[deg/s]",
        min_limit=-jnp.rad2deg(limits.max_angle_vel),
        max_limit=jnp.rad2deg(limits.max_angle_vel),
        reference=jnp.rad2deg(omegas_ref[:, 1]),
    )
    _simple_plot(
        axis=axes[0, 2],
        time=times,
        data=jnp.rad2deg(omegas[:, 2]),
        title="Z Angular Velocity",
        data_label="[deg/s]",
        min_limit=-jnp.rad2deg(limits.max_angle_vel),
        max_limit=jnp.rad2deg(limits.max_angle_vel),
        reference=jnp.rad2deg(omegas_ref[:, 2]),
    )

    #######################
    # linear acceleration #
    #######################

    # compute
    @jax.jit
    def get_lin_dyn(ts: opt.TrainState) -> tuple[jax.Array, jax.Array]:
        return ts.y_vest_irl[0, :3], ts.y_vest_sim[0, :3]

    lin_dyn = jnp.array([get_lin_dyn(ts)[0] for ts in trajectory])
    lin_dyn_ref = jnp.array([get_lin_dyn(ts)[1] for ts in trajectory])

    # plot
    _simple_plot(
        axis=axes[1, 0],
        time=times,
        data=lin_dyn[:, 0],
        title="X Linear Acceleration",
        data_label="[m/s^2]",
        min_limit=-limits.max_cart_acc,
        max_limit=limits.max_cart_acc,
        reference=lin_dyn_ref[:, 0],
    )
    _simple_plot(
        axis=axes[1, 1],
        time=times,
        data=lin_dyn[:, 1],
        title="Y Linear Acceleration",
        data_label="[m/s^2]",
        min_limit=-limits.max_cart_acc,
        max_limit=limits.max_cart_acc,
        reference=lin_dyn_ref[:, 1],
    )
    _simple_plot(
        axis=axes[1, 2],
        time=times,
        data=lin_dyn[:, 2],
        title="Z Linear Jerk",
        data_label="[m/s^2]",
        min_limit=-limits.max_cart_acc,
        max_limit=limits.max_cart_acc,
        reference=lin_dyn_ref[:, 2],
    )

    return fig


